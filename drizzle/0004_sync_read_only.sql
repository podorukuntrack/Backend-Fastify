CREATE OR REPLACE FUNCTION public.sync_enqueue_event()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    entity_name text := TG_ARGV[0];
    old_row jsonb := CASE WHEN TG_OP <> 'INSERT' THEN to_jsonb(OLD) ELSE NULL END;
    new_row jsonb := CASE WHEN TG_OP <> 'DELETE' THEN to_jsonb(NEW) ELSE NULL END;
    event_row jsonb;
    event_operation text;
    old_customer boolean := COALESCE(old_row->>'role', '') = 'customer';
    new_customer boolean := COALESCE(new_row->>'role', '') = 'customer';
BEGIN
    IF entity_name = 'customers' AND NOT old_customer AND NOT new_customer THEN
        IF TG_OP = 'DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
    END IF;

    IF TG_OP = 'DELETE' THEN
        event_operation := 'delete';
        event_row := old_row;
    ELSIF TG_OP = 'INSERT' THEN
        event_operation := 'insert';
        event_row := new_row;
    ELSIF entity_name = 'customers' AND old_customer AND NOT new_customer THEN
        event_operation := 'delete';
        event_row := old_row;
    ELSIF entity_name = 'customers' AND NOT old_customer AND new_customer THEN
        event_operation := 'insert';
        event_row := new_row;
    ELSE
        event_operation := 'update';
        event_row := new_row;
    END IF;

    INSERT INTO public.sync_outbox (entity, entity_id, operation, occurred_at, payload)
    VALUES (entity_name, (event_row->>'id')::uuid, event_operation, clock_timestamp(), public.sync_business_payload(entity_name, event_row));

    IF TG_OP = 'DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END;
$$;


            EXECUTE format('CREATE TRIGGER %I AFTER INSERT OR UPDATE OR DELETE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.sync_enqueue_event(%L)', 'sync_enqueue_' || item.table_name, item.table_name, item.entity_name);
        END IF;
    END LOOP;
END;
$$;
